#include <kernel/mr_kprintf.h>
#include <libc/mr_types.h>

int mr_kprintf(const char *fmt, ...) {
    mr_va_list args;
    int ret;

    mr_va_start(args, fmt);
    ret = mr_vprintf(fmt, args);
    mr_va_end(args);
    return ret;
}
